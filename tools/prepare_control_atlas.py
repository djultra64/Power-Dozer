#!/usr/bin/env python3
"""Extract the user-provided pixel atlas without redrawing or runtime assets."""
import argparse
from collections import deque
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw

ROOT=Path(__file__).resolve().parents[1]

def body_image(source,box,threshold,allow_touching_edges=()):
    crop=source.crop(tuple(box)).convert('RGB')
    width,height=crop.size
    pixels=list(crop.getdata())
    # Dark outline pixels stop the fill. Light keyboard interiors are kept
    # because they cannot be reached from the outer edges through that outline.
    def passable(i):
        r,g,b=pixels[i]
        return (299*r+587*g+114*b)>threshold*1000
    outside=set();queue=deque()
    for y in range(height):
        for x in (0,width-1):
            i=y*width+x
            if passable(i) and i not in outside:outside.add(i);queue.append(i)
    for x in range(width):
        for y in (0,height-1):
            i=y*width+x
            if passable(i) and i not in outside:outside.add(i);queue.append(i)
    def neighbors(i):
        x,y=i%width,i//width
        if x:yield i-1
        if x+1<width:yield i+1
        if y:yield i-width
        if y+1<height:yield i+width
    while queue:
        for i in neighbors(queue.popleft()):
            if i not in outside and passable(i):outside.add(i);queue.append(i)
    remaining=set(range(width*height))-outside
    components=[]
    while remaining:
        seed=min(remaining);remaining.remove(seed);component={seed};queue=deque([seed])
        while queue:
            for i in neighbors(queue.popleft()):
                if i in remaining:remaining.remove(i);component.add(i);queue.append(i)
        components.append(component)
    if not components:raise ValueError('No enclosed sprite body found')
    body=max(components,key=lambda part:(len(part),-min(part)))
    bounds=(min(i%width for i in body),min(i//width for i in body),max(i%width for i in body)+1,max(i//width for i in body)+1)
    touching=[i for i in range(4) if bounds[i]==(0,0,width,height)[i]]
    if any(i not in allow_touching_edges for i in touching):
        raise ValueError('Sprite body touches crop boundary; increase or correct its box')
    rgba=Image.new('RGBA',crop.size)
    data=[(*pixels[i],255) if i in body else (0,0,0,0) for i in range(width*height)]
    rgba.putdata(data)
    return rgba.crop(bounds),[box[0]+bounds[0],box[1]+bounds[1],box[0]+bounds[2],box[1]+bounds[3]]

def fit_sprite(body):
    width,height=body.size
    scale=32/max(width,height)
    resized=body.resize((max(1,round(width*scale)),max(1,round(height*scale))),Image.Resampling.NEAREST)
    result=Image.new('RGBA',(32,32))
    result.paste(resized,((32-resized.width)//2,(32-resized.height)//2))
    return result

def write_header(sprites,path):
    lines=['// Generated by tools/prepare_control_atlas.py; original supplied art, no redrawing.',
           '// Provenance and crop boxes: config/control-atlas.json. Rights review unresolved.',
           '#pragma once','#include <array>','#include <cstdint>','namespace bc {',
           'struct AtlasSprite { const char* name; std::array<uint32_t,1024> pixels; };',
           f'inline constexpr std::array<AtlasSprite,{len(sprites)}> control_atlas = {{{{']
    for name,im in sprites:
        values=[(r<<24)|(g<<16)|(b<<8)|a for r,g,b,a in im.getdata()]
        lines.append('    {"'+name+'", {{')
        lines.extend('        '+','.join(f'0x{v:08X}u' for v in values[i:i+16])+',' for i in range(0,1024,16))
        lines.append('    }}},')
    lines+=['}};','} // namespace bc','']
    path.parent.mkdir(parents=True,exist_ok=True);path.write_text('\n'.join(lines))

def contact_sheet(sprites,path,actual_size=False):
    columns=12;cell_w=112;cell_h=52 if actual_size else 116
    icon_size=32 if actual_size else 96
    canvas=Image.new('RGB',(columns*cell_w,((len(sprites)+columns-1)//columns)*cell_h),(70,75,80))
    draw=ImageDraw.Draw(canvas)
    for index,(name,im) in enumerate(sprites):
        x=(index%columns)*cell_w;y=(index//columns)*cell_h
        for cy in range(y,y+icon_size,8):
            for cx in range(x,x+icon_size,8):draw.rectangle((cx,cy,cx+7,cy+7),fill=(100,105,110) if ((cx-x)//8+(cy-y)//8)%2 else (135,140,145))
        preview=im if actual_size else im.resize((96,96),Image.Resampling.NEAREST)
        canvas.paste(preview,(x,y),preview)
        label=name.replace('playstation_','ps_').replace('generic_','gen_') if actual_size else name
        draw.text((x+1,y+icon_size+2),label,fill='white')
    path.parent.mkdir(parents=True,exist_ok=True);canvas.save(path)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=ROOT/'.local/evidence/control-atlas/source.png')
    parser.add_argument('--initial-source',type=Path,default=ROOT/'.local/evidence/control-atlas/source-initial.png')
    parser.add_argument('--config',type=Path,default=ROOT/'config/control-atlas.json')
    parser.add_argument('--output',type=Path,default=ROOT/'include/control_atlas_data.h')
    parser.add_argument('--contact',type=Path)
    parser.add_argument('--contact-32',type=Path)
    parser.add_argument('--report',type=Path)
    args=parser.parse_args();config=json.loads(args.config.read_text())
    digest=hashlib.sha256(args.source.read_bytes()).hexdigest()
    if digest!=config['provenance']['source_sha256']:raise ValueError('Source SHA256 does not match atlas provenance')
    source=Image.open(args.source).convert('RGB')
    if list(source.size)!=config['provenance']['source_dimensions']:raise ValueError('Source dimensions changed')
    sources={'complete':source};source_hashes={'complete':digest}
    for name,provenance in config['provenance'].get('sources',{}).items():
        if name=='complete':continue
        path=args.initial_source if name=='initial' else args.source.parent/provenance['file']
        sha=hashlib.sha256(path.read_bytes()).hexdigest()
        if sha!=provenance['sha256']:raise ValueError('Source SHA256 changed: '+name)
        image=Image.open(path).convert('RGB')
        if list(image.size)!=provenance['dimensions']:raise ValueError('Source dimensions changed: '+name)
        sources[name]=image;source_hashes[name]=sha
    sprites=[];report=[];names=set()
    for spec in config['sprites']:
        name=spec['name']
        if name in names:raise ValueError('Duplicate sprite '+name)
        names.add(name)
        try:body,bounds=body_image(sources[spec.get('source','complete')],spec['box'],config['extraction']['outline_threshold'],spec.get('allow_touching_edges',()))
        except ValueError as error:raise ValueError(name+': '+str(error)) from error
        sprite=fit_sprite(body);sprites.append((name,sprite))
        report.append({'name':name,'source':spec.get('source','complete'),'box':spec['box'],'body_bounds':bounds,'body_size':list(body.size),'rgba_sha256':hashlib.sha256(sprite.tobytes()).hexdigest(),'opaque_pixels':sum(a!=0 for r,g,b,a in sprite.getdata())})
    write_header(sprites,args.output)
    if args.contact:contact_sheet(sprites,args.contact)
    if args.contact_32:contact_sheet(sprites,args.contact_32,actual_size=True)
    metadata={'source_sha256':digest,'source_hashes':source_hashes,'header_sha256':hashlib.sha256(args.output.read_bytes()).hexdigest(),'sprites':report}
    if args.report:args.report.write_text(json.dumps(metadata,indent=2)+'\n')
    print(json.dumps({'sprites':len(sprites),'source_sha256':digest,'header_sha256':metadata['header_sha256']}))

if __name__=='__main__':main()
